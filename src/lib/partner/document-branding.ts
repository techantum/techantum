const VENDOR_NAME_PATTERN =
  /\b(tech\s*antum(?:\s+solutions)?|techantum(?:\s+solutions)?|partner portal)\b/gi;

export function stripVendorBranding(text: string, extraNames: Array<string | null | undefined> = []): string {
  let next = text.replace(VENDOR_NAME_PATTERN, 'the project team');
  for (const name of extraNames) {
    const trimmed = String(name || '').trim();
    if (trimmed.length < 3) continue;
    next = next.replace(new RegExp(trimmed.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'gi'), 'the client');
  }
  return next
    .replace(/prepared by:.*$/gim, '')
    .replace(/this document was generated by.*$/gim, '')
    .replace(/[ \t]{2,}/g, ' ')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}
