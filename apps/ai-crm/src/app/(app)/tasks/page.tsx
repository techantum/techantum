'use client';

import { FormEvent, useEffect, useMemo, useState } from 'react';
import {
  Badge,
  Btn,
  Card,
  Field,
  MetricCard,
  Modal,
  PageTitle,
  SkeletonRows,
  Tabs,
  inputClass} from '@/components/ui';
import { StatusBanner } from '@/components/StatusBanner';
import { api } from '@/lib/api-client';

export default function TasksPage() {
  const [rows, setRows] = useState<any[]>([]);
  const [leads, setLeads] = useState<any[]>([]);
  const [tab, setTab] = useState('team');
  const [selected, setSelected] = useState<any>(null);
  const [showCreate, setShowCreate] = useState(false);
  const [draft, setDraft] = useState({ title: '', leadId: '', priority: 'high' });
  const [loading, setLoading] = useState(true);

  async function load() {
    setLoading(true);
    const [tasks, leadRes] = await Promise.all([api('/api/v1/tasks'), api('/api/v1/leads?pageSize=100')]);
    setRows(tasks || []);
    setLeads(leadRes.items || []);
    setSelected(tasks?.[0] || null);
    setLoading(false);
  }

  useEffect(() => {
    load().catch(console.error);
  }, []);

  const metrics = useMemo(() => {
    const open = rows.filter((r) => r.status === 'open');
    const overdue = open.filter((r) => r.due_at && new Date(r.due_at) < new Date());
    const dueToday = open.filter((r) => r.due_at && new Date(r.due_at).toDateString() === new Date().toDateString());
    return {
      pending: open.length,
      overdue: overdue.length,
      dueToday: dueToday.length,
      completed: rows.filter((r) => r.status === 'done').length,
    };
  }, [rows]);

  const filtered = rows.filter((r) => {
    if (tab === 'overdue') return r.status === 'open' && r.due_at && new Date(r.due_at) < new Date();
    if (tab === 'upcoming') return r.status === 'open';
    if (tab === 'completed') return r.status === 'done';
    return true;
  });

  async function create(e: FormEvent) {
    e.preventDefault();
    await api('/api/v1/tasks', {
      method: 'POST',
      body: JSON.stringify({
        title: draft.title,
        leadId: draft.leadId || null,
        priority: draft.priority,
        dueAt: new Date(Date.now() + 86400000).toISOString()})});
    setShowCreate(false);
    setDraft({ title: '', leadId: '', priority: 'high' });
    await load();
  }

  async function complete(id: string) {
    await api(`/api/v1/tasks/${id}`, { method: 'PATCH', body: JSON.stringify({ status: 'done' }) });
    await load();
  }

  if (loading) return <SkeletonRows rows={8} />;

  return (
    <div>
      <PageTitle
        title="Tasks & Follow-ups"
        subtitle="Human follow-ups generated by workflows and sales ownership."
        actions={<Btn onClick={() => setShowCreate(true)}>Create task</Btn>}
      />
      <StatusBanner>Overdue follow-ups notify the owner and Sales Manager in production notification channels.</StatusBanner>

      <div className="mb-4 grid gap-3 sm:grid-cols-2 lg:grid-cols-4">
        <MetricCard label="Pending follow-ups" value={metrics.pending} />
        <MetricCard label="Overdue" value={metrics.overdue} tone="warn" />
        <MetricCard label="Due today" value={metrics.dueToday} />
        <MetricCard label="Completed" value={metrics.completed} tone="ok" />
      </div>

      <Tabs
        value={tab}
        onChange={setTab}
        items={[
          { id: 'team', label: `Team tasks · ${rows.length}` },
          { id: 'overdue', label: `Overdue · ${metrics.overdue}` },
          { id: 'upcoming', label: `Upcoming · ${metrics.pending}` },
          { id: 'completed', label: `Completed · ${metrics.completed}` },
        ]}
      />

      <div className="grid gap-4 xl:grid-cols-[minmax(0,1.3fr)_320px]">
        <Card className="overflow-hidden">
          <table className="min-w-full text-left text-sm">
            <thead className="bg-slate-50 text-[11px] uppercase text-slate-500">
              <tr>
                <th className="px-3 py-3">Task / linked lead</th>
                <th className="px-3 py-3">Owner</th>
                <th className="px-3 py-3">Due</th>
                <th className="px-3 py-3">Priority / state</th>
              </tr>
            </thead>
            <tbody>
              {filtered.map((row) => (
                <tr
                  key={row.id}
                  onClick={() => setSelected(row)}
                  className={`cursor-pointer border-t border-slate-100 hover:bg-violet-50/40 ${selected?.id === row.id ? 'bg-violet-50/60' : ''}`}
                >
                  <td className="px-3 py-3">
                    <div className="font-medium">{row.title}</div>
                    <div className="text-[11px] text-slate-400">{row.lead_name || 'No linked lead'}</div>
                  </td>
                  <td className="px-3 py-3">{row.assignee_name || 'Unassigned'}</td>
                  <td className="px-3 py-3 text-xs">{row.due_at ? new Date(row.due_at).toLocaleString() : '—'}</td>
                  <td className="px-3 py-3">
                    <div className="flex flex-wrap gap-1">
                      <Badge tone={row.priority === 'high' ? 'orange' : 'slate'}>{row.priority}</Badge>
                      <Badge tone={row.status === 'done' ? 'green' : row.due_at && new Date(row.due_at) < new Date() ? 'rose' : 'purple'}>
                        {row.status}
                      </Badge>
                    </div>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </Card>

        <Card className="p-4">
          <h3 className="font-semibold">Task detail</h3>
          {selected ? (
            <div className="mt-3 space-y-3 text-sm">
              <div className="text-xs text-slate-400">{selected.id.slice(0, 8)}</div>
              <div className="font-medium text-slate-900">{selected.title}</div>
              <div>Lead: {selected.lead_name || '—'}</div>
              <div>Owner: {selected.assignee_name || 'Unassigned'}</div>
              <div>Due: {selected.due_at ? new Date(selected.due_at).toLocaleString() : '—'}</div>
              {selected.status !== 'done' ? (
                <Btn onClick={() => complete(selected.id)}>Mark complete</Btn>
              ) : (
                <Badge tone="green">Completed</Badge>
              )}
            </div>
          ) : (
            <p className="mt-3 text-slate-400">Select a task</p>
          )}
        </Card>
      </div>

      {showCreate ? (
        <Modal title="Create task" onClose={() => setShowCreate(false)}>
          <form onSubmit={create} className="space-y-3">
            <Field label="Task title">
              <input className={inputClass} required value={draft.title} onChange={(e) => setDraft({ ...draft, title: e.target.value })} />
            </Field>
            <Field label="Linked lead">
              <select className={inputClass} value={draft.leadId} onChange={(e) => setDraft({ ...draft, leadId: e.target.value })}>
                <option value="">None</option>
                {leads.map((l) => (
                  <option key={l.id} value={l.id}>
                    {l.full_name || l.phone}
                  </option>
                ))}
              </select>
            </Field>
            <Field label="Priority">
              <select className={inputClass} value={draft.priority} onChange={(e) => setDraft({ ...draft, priority: e.target.value })}>
                <option value="high">High</option>
                <option value="medium">Medium</option>
                <option value="low">Low</option>
              </select>
            </Field>
            <div className="flex justify-end gap-2">
              <Btn variant="secondary" type="button" onClick={() => setShowCreate(false)}>
                Cancel
              </Btn>
              <Btn type="submit">Create task</Btn>
            </div>
          </form>
        </Modal>
      ) : null}
    </div>
  );
}
